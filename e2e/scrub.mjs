import { chromium } from 'playwright-core';
const BASE='http://localhost:5173';
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1440,height:960}});
const errs=[];p.on('pageerror',e=>errs.push(e.message.slice(0,160)));
await p.goto(BASE+'/',{waitUntil:'networkidle'});
await p.waitForTimeout(1600);
const imgWrap=p.locator('div.absolute.inset-0.will-change-transform').first();
const content=p.locator('div.relative.z-10.flex.flex-1.flex-col');
const st=async el=>el.evaluate(e=>({y:new DOMMatrix(getComputedStyle(e).transform).m42,op:getComputedStyle(e).opacity}));
console.log('at top        :',JSON.stringify(await st(imgWrap)), 'content', JSON.stringify(await st(content)));
await p.mouse.wheel(0,700); await p.waitForTimeout(1500);
console.log('scrolled 700  :',JSON.stringify(await st(imgWrap)), 'content', JSON.stringify(await st(content)));
await p.mouse.wheel(0,900); await p.waitForTimeout(1500);
console.log('scrolled 1600 :',JSON.stringify(await st(imgWrap)), 'content', JSON.stringify(await st(content)));
await p.evaluate(()=>scrollTo(0,0)); await p.waitForTimeout(900);
console.log('back to top   :',JSON.stringify(await st(imgWrap)), 'content', JSON.stringify(await st(content)));
console.log('errs:',errs.length?errs:'none');
await b.close();
